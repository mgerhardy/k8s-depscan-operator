#!/usr/bin/env bash
# Regenerate the vendored half of the Helm chart from config/.
#
# The chart ships two kinds of templates:
#
#   1. VENDORED, generated here -- templates/crds.yaml and templates/rbac.yaml.
#      These are copied verbatim from the controller-gen output under config/crd
#      and config/rbac so they can never drift from the controllers that
#      watch/write them. They are NOT hand-edited; re-run this script after
#      `make generate` whenever the api/ types or RBAC markers change.
#
#   2. HAND-WRITTEN, Helm-templated -- templates/namespace.yaml,
#      templates/deployment.yaml, templates/service.yaml,
#      templates/depscanconfig.yaml, templates/NOTES.txt, _helpers.tpl. These
#      expose the image, resources and placement as values and are maintained
#      by hand; this script leaves them untouched.
#
# The namespace is the one knob that cuts across both halves. config/ hard-codes
# `depscan-system`; the chart makes it `.Values.namespace`. For the vendored
# RBAC we therefore rewrite the literal namespace to the Helm value as the files
# are copied -- the only transform applied to generated output.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

chart_templates="charts/depscan-operator/templates"
ns_literal="depscan-system"
# Helm expression the literal namespace is rewritten to. Single-quoted so the
# shell leaves it verbatim for sed to emit into the YAML.
ns_expr='{{ .Values.namespace }}'

gen_header() {
  # $1: what, $2: source path(s)
  cat <<EOF
# DO NOT EDIT. Generated by hack/gen-helm-chart.sh from $2.
# Vendored verbatim from the controller-gen output so it cannot drift from the
# binary that watches/writes these resources. Re-run \`make helm\` after
# \`make generate\` to refresh. Hand edits are overwritten.
EOF
}

echo ">> crds.yaml (verbatim, cluster-scoped -- no namespace rewrite)"
{
  gen_header "CRDs" "config/crd/depscan.io_*.yaml"
  cat config/crd/depscan.io_depscanconfigs.yaml
  cat config/crd/depscan.io_depscanreports.yaml
} > "$chart_templates/crds.yaml"

echo ">> rbac.yaml (namespace literal -> .Values.namespace)"
{
  gen_header "RBAC" "config/rbac/{role,service_account,metrics_reader_role,report_viewer_role}.yaml"
  # role.yaml first (ClusterRole + namespaced Role), then service_account.yaml
  # (the ServiceAccount plus every binding and the leader-election Role), then
  # the aggregated viewer and metrics-reader ClusterRoles -- the exact set the
  # config/ kustomization installs.
  for f in \
    config/rbac/role.yaml \
    config/rbac/service_account.yaml \
    config/rbac/metrics_reader_role.yaml \
    config/rbac/report_viewer_role.yaml; do
    echo "---"
    echo "# source: $f"
    cat "$f"
  done
} | sed "s/\bnamespace: ${ns_literal}\b/namespace: ${ns_expr}/g" > "$chart_templates/rbac.yaml"

echo ">> done. Review with: git diff $chart_templates"
